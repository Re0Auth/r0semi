// The single-source kit-config gate.
//
// This project deliberately has NO `svelte.config.js`. The SvelteKit config —
// the static adapter, `paths.base = '/app'`, the runes compiler option and the
// CSP — lives inline in `vite.config.ts` inside the `sveltekit({...})` call.
// That is a choice, not an omission: `paths.base` must equal
// `internal/webui.BasePath`, and keeping adapter + base + CSP next to the Vite
// server/proxy config means the frontend's whole build posture is readable in
// one file. See web/README.md.
//
// What this gate refuses is a *second* configuration appearing beside it. The
// moment a `svelte.config.*` exists, SvelteKit reads that file for the adapter
// and paths and IGNORES the inline `sveltekit({...})` options — so the two
// diverge silently: the build keeps working, the base path or the CSP quietly
// changes, and the file a reviewer reads is no longer the one that ships.
// Nothing else in the build notices, which is exactly why it is a check.
//
// Usage: node scripts/check-kit-config.mjs

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(here, '..'); // web/
const repoRoot = join(projectRoot, '..');

// Every extension SvelteKit / Vite will load a config from. A plain `.js` is the
// common one, but a `.ts`/`.mjs` config is read too, so a check that matched only
// the first would be bypassed by a rename.
const KIT_CONFIG = /^svelte\.config\.(js|ts|mjs|cjs|mts|cts)$/;

// Directories that are not project sources: dependencies ship their own
// svelte.config.js files and a build output is not a configuration. `.svelte-kit`
// is generated by `svelte-kit sync`.
const SKIP = new Set(['node_modules', '.git', '.svelte-kit', 'build', 'dist', 'test-results', 'playwright-report']);

function walk(dir) {
	const out = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.isDirectory()) {
			if (SKIP.has(entry.name)) continue;
			out.push(...walk(join(dir, entry.name)));
		} else {
			out.push(join(dir, entry.name));
		}
	}
	return out;
}

// Scan the web project and the repository root: SvelteKit resolves the config
// from the project directory, but a stray file at the root is the same mistake
// one level up (and a person looking for the config would find it there).
const scanned = [];
const offenders = new Set();
for (const dir of [projectRoot, repoRoot]) {
	let files;
	try {
		files = walk(dir);
	} catch (err) {
		console.error(`kit-config: cannot read ${dir}: ${err.message}`);
		process.exit(1);
	}
	for (const file of files) {
		scanned.push(file);
		const name = file.slice(file.lastIndexOf('\\') + 1).split('/').pop();
		if (KIT_CONFIG.test(name)) offenders.add(relative(repoRoot, file));
	}
}

// Anti-vacuous: this check passes by finding nothing, which is also what a walk
// that stopped reading the tree looks like — and the "inline in vite.config.ts"
// claim above is only true while that inline config is actually there. If the
// config has moved, this gate should be deleted deliberately, not left green.
const viteConfig = join(projectRoot, 'vite.config.ts');
if (!existsSync(viteConfig)) {
	console.error(`kit-config: ${viteConfig} does not exist; the inline kit config is gone, so this gate no longer means anything`);
	process.exit(1);
}
const vite = readFileSync(viteConfig, 'utf8');
for (const needed of ['sveltekit(', 'adapter(', 'paths:']) {
	if (!vite.includes(needed)) {
		console.error(`kit-config: ${viteConfig} does not contain ${needed}, so the kit config is not inline there any more; update or remove this gate`);
		process.exit(1);
	}
}
if (scanned.length < 20) {
	console.error(`kit-config: only ${scanned.length} files were scanned; the walk is not reading the project`);
	process.exit(1);
}

if (offenders.size > 0) {
	console.error(
		'kit-config: a svelte.config.* exists, which is a SECOND SvelteKit configuration:\n' +
			[...offenders].map((f) => `      ${f}`).join('\n') +
			'\n  SvelteKit reads that file for the adapter and paths and ignores the inline\n' +
			'  sveltekit({...}) options in web/vite.config.ts, so the two drift silently.\n' +
			'  Keep the one config in web/vite.config.ts (see web/README.md) and delete this file.'
	);
	process.exit(1);
}

console.log(`kit-config: no svelte.config.* anywhere (scanned ${scanned.length} files); the kit config is inline in web/vite.config.ts`);
